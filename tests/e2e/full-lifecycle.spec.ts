// ── Step 12: Final graph state is consistent ──

test("final graph state is consistent", async ({ request }) => {
  const res = await request.get("/api/graph");
  const graph = await res.json();

  // 3 declarations from onboarding
  expect(graph.declarations.length).toBe(3);

  // At least 2 milestones from derive
  expect(graph.milestones.length).toBeGreaterThanOrEqual(2);

  // At least 2 actions from plan
  expect(graph.actions.length).toBeGreaterThanOrEqual(2);

  // Stats match
  expect(graph.stats.declarations).toBe(graph.declarations.length);
  expect(graph.stats.milestones).toBe(graph.milestones.length);
  expect(graph.stats.actions).toBe(graph.actions.length);

  // No validation errors
  expect(graph.validation.errors).toEqual([]);

  // Project was renamed during onboarding
  expect(graph.projectName).toBe("MD2PDF Pro");
});

// ── Step 13: Agent history shows all runs ──

test("agent history shows complete run log", async ({ request }) => {
  const res = await request.get("/api/agents");
  const agents = await res.json();

  // Should have at least: derive, plan-actions, execute, verify
  expect(agents.length).toBeGreaterThanOrEqual(4);

  const types = agents.map((a: any) => a.type);
  expect(types).toContain("derivation");
  expect(types).toContain("execution");
  expect(types).toContain("verification");

  // All should be completed
  const statuses = agents.map((a: any) => a.status);
  expect(statuses.every((s: string) => s === "completed")).toBe(true);
});

