import { test, expect } from "@playwright/test";
import { existsSync, mkdirSync, rmSync, writeFileSync, readFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

/**
 * Full lifecycle E2E test with mocked AI responses.
 *
 * Runs against a clean .planning/ folder in a temp directory.
 * The server runs with DCL_MOCK_AI pointing to fixture responses,
 * so all AI calls return deterministic data while the real server
 * code (parsing, file writing, SSE, graph building) runs normally.
 *
 * Flow: empty project → onboarding → declarations → derive milestones
 *       → plan actions → execute → verify
 */

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = resolve(__dirname, "../..");
const TMP = resolve(PROJECT_ROOT, "test-results/lifecycle-project");

test.describe.configure({ mode: "serial" });

test.beforeAll(() => {
  // Create a clean project directory
  if (existsSync(TMP)) rmSync(TMP, { recursive: true });
  mkdirSync(resolve(TMP, ".planning"), { recursive: true });
  writeFileSync(
    resolve(TMP, ".planning", "FUTURE.md"),
    "# Future: Project\n",
    "utf-8"
  );
  writeFileSync(
    resolve(TMP, ".planning", "MILESTONES.md"),
    [
      "# Milestones: Project",
      "",
      "## Milestones",
      "",
      "| ID | Title | Status | Realizes | Plan | Review |",
      "|----|-------|--------|----------|------|--------|",
      "",
    ].join("\n"),
    "utf-8"
  );
  writeFileSync(
    resolve(TMP, ".planning", "config.json"),
    '{\n  "commit_docs": true\n}\n',
    "utf-8"
  );
});

test.afterAll(() => {
  // Clean up — comment this out to inspect state after test
  // if (existsSync(TMP)) rmSync(TMP, { recursive: true });
});

// ── Step 1: Empty project shows onboarding ──

test("empty project shows onboarding screen", async ({ page }) => {
  await page.goto("/");
  await page.waitForLoadState("domcontentloaded");

  // Should show the onboarding flow
  await expect(
    page.getByText("What is true when this project succeeds?")
  ).toBeVisible({ timeout: 10_000 });

  // Vision textarea should be present
  await expect(
    page.getByPlaceholder("When this project succeeds...")
  ).toBeVisible();
});

