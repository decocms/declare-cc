// ── Step 6: Derive milestones via mocked AI ──

test("derive milestones for D-01", async ({ request }) => {
  const res = await request.post("/api/agents/derive", {
    data: { declarationId: "D-01" },
  });
  expect(res.ok()).toBe(true);
  const agent = await res.json();
  expect(agent.type).toBe("derivation");
  expect(agent.status).toBe("running");

  // Wait for the mocked AI to complete (100ms delay + file write)
  await new Promise((r) => setTimeout(r, 2000));

  // Check agent completed
  const agentRes = await request.get(`/api/agents/${agent.id}`);
  const updated = await agentRes.json();
  expect(updated.status).toBe("completed");

  // Verify milestones were written
  const graph = await (await request.get("/api/graph")).json();
  expect(graph.milestones.length).toBeGreaterThanOrEqual(2);
  expect(graph.milestones.some((m: any) => m.id === "M-01")).toBe(true);
});

